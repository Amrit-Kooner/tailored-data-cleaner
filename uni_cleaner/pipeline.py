# pipeline.py
"""
The conductor. This file answers ONE question: "in what order does the
cleaning happen?" -- read the step lists below top to bottom.

Every step is  step(df, ctx) -> df  (see models.RunContext). Steps decorated
@value_only (see guards.py) are additionally checked so they can never turn a
populated value into a blank. To add a cleaning step, write the function in
the right steps/ module and add one line to a list here.

This pipeline has no AI dependency: no model is loaded and no column is
generated by anything other than deterministic rules.
"""

